// Helper to look up an order by ID or AWB
export const findCustomerOrder = (query) => {
  if (!query) return CUSTOMER_ORDERS_DATA[0];
  const cleaned = query.trim().toUpperCase().replace('#', '');
  const found = CUSTOMER_ORDERS_DATA.find(
    (o) =>
      o.orderId.toUpperCase() === cleaned ||
      o.awbNumber.toUpperCase() === cleaned ||
      o.orderId.toUpperCase().includes(cleaned) ||
      o.awbNumber.toUpperCase().includes(cleaned)
  );
  return found || CUSTOMER_ORDERS_DATA[0];
};
